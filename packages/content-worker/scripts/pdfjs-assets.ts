/**
 * Writes src/services/pdfjsAssets.ts: the pdf.js files the content Worker's
 * PDF viewer serves beside a PDF version (src/services/pdfViewer.ts), each
 * imported from the pinned pdfjs-dist (the Worker's bundle carries them as
 * Text and Data modules: wrangler.jsonc's rules) with its path,
 * size and SHA-256. Run after changing the pdfjs-dist version:
 *   pnpm run generate:pdfjs-assets
 * (test/raft-content.test.ts fails while the file is stale).
 */
import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";

const ROOT = "node_modules/pdfjs-dist";

/** What the viewer serves: the library and its worker, CMaps, standard fonts, decoders, ICC profiles, licenses. */
export async function pdfjsAssetList(): Promise<string[]> {
  const list = async (dir: string, keep: (name: string) => boolean) => (await readdir(`${ROOT}/${dir}`)).filter(keep).sort().map((name) => `${dir}/${name}`);
  return [
    "build/pdf.min.mjs",
    "build/pdf.worker.min.mjs",
    ...(await list("cmaps", (name) => name.endsWith(".bcmap"))),
    ...(await list("standard_fonts", (name) => /\.(pfb|ttf)$/.test(name))),
    // JPEG 2000, JBIG2 and colour management; never quickjs (PDF scripting stays off).
    "wasm/jbig2.wasm",
    "wasm/openjpeg.wasm",
    "wasm/qcms_bg.wasm",
    ...(await list("iccs", (name) => name.endsWith(".icc"))),
    "LICENSE",
    ...(await list("cmaps", (name) => name.startsWith("LICENSE"))),
    ...(await list("standard_fonts", (name) => name.startsWith("LICENSE"))),
    ...(await list("wasm", (name) => name.startsWith("LICENSE"))),
    ...(await list("iccs", (name) => name.startsWith("LICENSE"))),
  ];
}

/** The module's source for the installed pdfjs-dist. */
export async function pdfjsAssetsSource(): Promise<string> {
  const { version } = JSON.parse(await readFile(`${ROOT}/package.json`, "utf8"));
  const lines: string[] = [];
  const entries: string[] = [];
  for (const [index, path] of (await pdfjsAssetList()).entries()) {
    const bytes = await readFile(`${ROOT}/${path}`);
    const sha256 = createHash("sha256").update(bytes).digest("hex");
    lines.push(`import a${index} from "pdfjs-dist/${path}";`);
    // Served under the viewer's directory: the library at its top, the rest by their pdfjs-dist path.
    const served = path.startsWith("build/") ? path.slice("build/".length) : path === "LICENSE" ? "LICENSE-pdfjs" : path;
    entries.push(`  [${JSON.stringify(served)}, a${index}, ${bytes.byteLength}, ${JSON.stringify(sha256)}],`);
  }
  return `// Generated by scripts/pdfjs-assets.ts from pdfjs-dist ${version}: don't edit.
// @ts-nocheck: these modules are Text and Data (wrangler.jsonc's rules), not pdf.js's own typings.
${lines.join("\n")}

export const PDFJS_VERSION = ${JSON.stringify(version)};

/** [path under the viewer's directory, its bytes (text or binary), size, SHA-256]. */
export const PDFJS_ASSETS: ReadonlyArray<readonly [string, string | ArrayBuffer, number, string]> = [
${entries.join("\n")}
];
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile("src/services/pdfjsAssets.ts", await pdfjsAssetsSource());
  console.log("wrote src/services/pdfjsAssets.ts");
}
