function formatUnreadChannelLines(unreadSummary: Record<string, number>): string {
  let lines = "";
  for (const [ch, count] of Object.entries(unreadSummary)) {
    lines += `\n- ${ch}: ${count} unread`;
  }
  return lines;
}

