export function inboxProjectionTraceAttrs(
  rows: readonly AgentInboxTargetRow[],
  pendingMessageCount: number,
): Record<string, unknown> {
  let maxPendingCount = 0;
  let mentionTargetCount = 0;
  let threadTargetCount = 0;
  let dmTargetCount = 0;
  let taskTargetCount = 0;
  let attentionHintTargetCount = 0;
  for (const row of rows) {
    maxPendingCount = Math.max(maxPendingCount, row.pendingCount);
    if (row.flags.includes("mention")) mentionTargetCount += 1;
    if (row.flags.includes("thread")) threadTargetCount += 1;
    if (row.flags.includes("dm")) dmTargetCount += 1;
    if (row.flags.includes("task")) taskTargetCount += 1;
    if (row.attentionHint) attentionHintTargetCount += 1;
  }
  return {
    target_count: rows.length,
    changed_target_count: rows.length,
    inbox_target_count: rows.length,
    pending_message_count: pendingMessageCount,
    max_pending_per_target: maxPendingCount,
    mention_target_count: mentionTargetCount,
    thread_target_count: threadTargetCount,
    dm_target_count: dmTargetCount,
    task_target_count: taskTargetCount,
    attention_hint_target_count: attentionHintTargetCount,
  };
}

export function projectThreadJoinContextsForRuntimeInput(
  messages: readonly AgentMessage[],
  getVisibleBoundary: (target: string) => number | undefined,
  renderContext = true,
): { messages: AgentMessage[]; renderedContextMessages: AgentMessage[] } {
  const selectedIndexByTarget = new Map<string, number>();
  for (let index = 0; renderContext && index < messages.length; index += 1) {
    const context = messages[index].thread_join_context;
    if (context && getVisibleBoundary(context.thread_target) === undefined) {
      selectedIndexByTarget.set(context.thread_target, index);
    }
  }

  const renderedContextMessages: AgentMessage[] = [];
  const projectedMessages = messages.map((message, index) => {
    const context = message.thread_join_context;
    if (!context) return message;
    if (selectedIndexByTarget.get(context.thread_target) === index) {
      renderedContextMessages.push(message);
      return message;
    }
    const { thread_join_context: _omitted, ...projected } = message;
    return projected;
  });
  return { messages: projectedMessages, renderedContextMessages };
}

