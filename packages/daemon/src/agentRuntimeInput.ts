// AxSurfaceText brand + mint live in @botiverse/raft-shared (next to Brand, per
// brandedIds doctrine) so drivers/types can name the type without a cycle.
export type { AxSurfaceText } from "@botiverse/raft-shared";

export interface AxSurfaceExample<A extends readonly unknown[]> {
  readonly title?: string;
  /** One invocation's arguments, typechecked against the formatter's own parameter tuple. */
  readonly args: A;
}

export interface AxSurfaceOptions<A extends readonly unknown[]> {
  /** REQUIRED and non-empty (@xxchan ruling): a surface without an example does not compile. */
  readonly examples: readonly [AxSurfaceExample<A>, ...AxSurfaceExample<A>[]];
}

export type AxSurfaceMeta<A extends readonly unknown[]> = {
  readonly axDescription: string;
  readonly axExamples: readonly AxSurfaceExample<A>[];
};

/**
 * Define a registered agent-visible runtime-input surface. Sole public brand
 * outlet on the daemon side (besides the pinned adoptAxSurfaceText escape):
 * the ax-surfaces manifest is generated by scanning `axSurface(`/
 * `axSurfaceLiteral(` call sites, so defining a surface and registering it are
 * the same act. Description AND at least one typed example live in the same
 * expression; the AX HTML renders fn(...example.args) via the attached
 * axExamples. Descriptions must be string literals.
 */
export function axSurface<A extends readonly unknown[]>(
  description: string,
  format: (...args: A) => string,
  options: AxSurfaceOptions<A>,
): ((...args: A) => AxSurfaceText) & AxSurfaceMeta<A>;
export function axSurface<A extends readonly unknown[]>(
  description: string,
  format: (...args: A) => string | null,
  options: AxSurfaceOptions<A>,
): ((...args: A) => AxSurfaceText | null) & AxSurfaceMeta<A>;
export function axSurface<A extends readonly unknown[]>(
  description: string,
  format: (...args: A) => string | null,
  options: AxSurfaceOptions<A>,
): ((...args: A) => AxSurfaceText | null) & AxSurfaceMeta<A> {
  const wrapped = (...args: A) => format(...args) as AxSurfaceText | null;
  return Object.assign(wrapped, { axDescription: description, axExamples: options.examples });
}

/** Literal (argument-free) registered surface. */
export function axSurfaceLiteral(description: string, text: string): AxSurfaceText {
  void description;
  return text as AxSurfaceText;
}

export function composeAxSurfaces(...parts: readonly AxSurfaceText[]): AxSurfaceText {
  return asAxSurfaceText(parts.join(""));
}

/**
 * Adapter-boundary escape hatch for runtime input that is not produced by a
 * registered formatter in this turn: a resume prompt restored from persisted
 * state, and a standing prompt built by the driver (itself the registered
 * standing_prompt surface, typed at the RuntimeDriver seam as string).
 * Do not add call sites to satisfy the compiler — register a formatter
 * instead. The registry drift test pins the exact call-site count in
 * agentProcessManager.ts.
 */
export const adoptAxSurfaceText = (text: string): AxSurfaceText => asAxSurfaceText(text);

type IncomingMessageFormatOptions = {
  attachmentHint?: AttachmentDownloadHintStyle;
};

function getMessageShortId(messageId: string): string {
  return messageId.startsWith("thread-") ? messageId.slice(7) : messageId.slice(0, 8);
}

function formatSenderHandle(message: { sender_name: string; sender_description?: string | null }): string {
  return message.sender_description
    ? `@${message.sender_name} — ${message.sender_description}`
    : `@${message.sender_name}`;
}

function formatVisibleActorType(type: AgentMessage["sender_type"]): string {
  return ` type=${type}`;
}

function formatThreadContextMessage(
  message: NonNullable<AgentMessage["thread_join_context"]>["parent_message"],
): string {
  const msgId = message.message_id ? getMessageShortId(message.message_id) : "-";
  const time = message.timestamp ? formatUtcTimestamp(message.timestamp) : "-";
  const senderType = formatVisibleActorType(message.sender_type);
  const seq = typeof message.seq === "number" ? ` seq=${message.seq}` : "";
  return `- [msg=${msgId}${seq} time=${time}${senderType}] ${formatSenderHandle(message)}: ${message.content}`;
}

function formatIncomingMessage(message: AgentMessage, options: IncomingMessageFormatOptions): string {
  const threadJoinPrefix = message.thread_join_context
    ? [
        "[Raft thread context: you were mentioned in a thread without model-visible context.]",
        `parent: ${message.thread_join_context.parent_target}`,
        `thread: ${message.thread_join_context.thread_target}`,
        `suggested next step: raft message read --target "${message.thread_join_context.suggested_read_history_target}"`,
        "",
        "Parent message:",
        formatThreadContextMessage(message.thread_join_context.parent_message),
        "",
        `Recent thread context${message.thread_join_context.history_truncated ? " (truncated)" : ""}:`,
        message.thread_join_context.recent_messages.length > 0
          ? message.thread_join_context.recent_messages.map(formatThreadContextMessage).join("\n")
          : "- (no earlier thread replies)",
        "",
      ].join("\n")
    : "";
  const threadFollowReactivationPrefix = message.thread_follow_reactivation
    ? [
        `[Raft thread follow restored: this @mention re-subscribed you to ordinary replies in ${message.thread_follow_reactivation.thread_target}.]`,
        `To stop those replies again: raft thread unfollow --target ${JSON.stringify(message.thread_follow_reactivation.thread_target)}`,
        "",
      ].join("\n")
    : "";
  const target = formatAgentMessageVisibleTarget(message);
  const msgId = message.message_id ? getMessageShortId(message.message_id) : "-";
  const time = message.timestamp ? formatUtcTimestamp(message.timestamp) : "-";
  const senderType = formatVisibleActorType(message.sender_type);
  const attachSuffix = formatAttachmentSuffix(message.attachments, options.attachmentHint);
  const taskSuffix = message.task_status
    ? ` [task #${message.task_number} status=${message.task_status}${message.task_assignee_id ? ` assignee=${message.task_assignee_type ?? null}:${message.task_assignee_id}` : ""}]`
    : "";
  const lineageSuffix = formatProducerFactLineageBracket(message.producerFactId);
  const body = `[target=${target} msg=${msgId} time=${time}${senderType}] ${formatSenderHandle(message)}: ${message.content}${message.third_party_event ? `\npayload:\n${renderThirdPartyInertJson(message.third_party_event.payload)}` : ""}${attachSuffix}${taskSuffix}${lineageSuffix}${formatAgentReplyAffordanceSuffix(message)}`;
  const prefixes = [threadJoinPrefix, threadFollowReactivationPrefix].filter(Boolean);
  return prefixes.length > 0 ? `${prefixes.join("\n")}\n${body}` : body;
}

function incomingMessageFormatOptionsForDriver(driver: RuntimeDriver): IncomingMessageFormatOptions {
  switch (driver.communication.chat) {
    case "slock_cli":
      return { attachmentHint: "slock_cli" };
  }
}

