export interface AxSurfaceExample<A extends readonly unknown[]> {
  readonly title?: string;
  /** One invocation's arguments, typechecked against the formatter's own parameter tuple. */
  readonly args: A;
}

export interface AxSurfaceOptions<A extends readonly unknown[]> {
  /** REQUIRED and non-empty (@xxchan ruling): a surface without an example does not compile. */
  readonly examples: readonly [AxSurfaceExample<A>, ...AxSurfaceExample<A>[]];
}

export type AxSurfaceMeta<A extends readonly unknown[]> = {
  readonly axDescription: string;
  readonly axExamples: readonly AxSurfaceExample<A>[];
};

/**
 * Define a registered agent-visible runtime-input surface. Sole public brand
 * outlet on the daemon side (besides the pinned adoptAxSurfaceText escape):
 * the ax-surfaces manifest is generated by scanning `axSurface(`/
 * `axSurfaceLiteral(` call sites, so defining a surface and registering it are
 * the same act. Description AND at least one typed example live in the same
 * expression; the AX HTML renders fn(...example.args) via the attached
 * axExamples. Descriptions must be string literals.
 */
export function axSurface<A extends readonly unknown[]>(
  description: string,
  format: (...args: A) => string,
  options: AxSurfaceOptions<A>,
): ((...args: A) => AxSurfaceText) & AxSurfaceMeta<A>;
export function axSurface<A extends readonly unknown[]>(
  description: string,
  format: (...args: A) => string | null,
  options: AxSurfaceOptions<A>,
): ((...args: A) => AxSurfaceText | null) & AxSurfaceMeta<A>;
export function axSurface<A extends readonly unknown[]>(
  description: string,
  format: (...args: A) => string | null,
  options: AxSurfaceOptions<A>,
): ((...args: A) => AxSurfaceText | null) & AxSurfaceMeta<A> {
  const wrapped = (...args: A) => format(...args) as AxSurfaceText | null;
  return Object.assign(wrapped, { axDescription: description, axExamples: options.examples });
}

/** Literal (argument-free) registered surface. */
export function axSurfaceLiteral(description: string, text: string): AxSurfaceText {
  void description;
  return text as AxSurfaceText;
}

export function composeAxSurfaces(...parts: readonly AxSurfaceText[]): AxSurfaceText {
  return asAxSurfaceText(parts.join(""));
}

