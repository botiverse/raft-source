// task #333: the default `Next action` for a daemon-proxy 5xx must follow the
// proxy's failure_class. For upstream_http_response the daemon discards the
// upstream body and logs only status + codes, so pointing the reader at the
// daemon proxy transport log cannot answer "what did the server say".
import assert from "node:assert/strict";

import { apiFailureError, proxyFailureNextAction, rateLimitedResponseError } from "./apiFailure";

const AGENT_STEP =
  "Retry once in a few seconds; if the command writes something, first check whether it already took effect, so it is not done twice. "
  + "If it keeps failing, tell your Computer's owner and include the correlation id. For whoever investigates: ";
const TRANSPORT_LOG_HINT =
  AGENT_STEP + "This 5xx was generated by the local daemon proxy; use the correlation id to inspect daemon proxy transport logs before attributing it to the server.";

test("every proxy failure class starts with what the agent itself can do, then the diagnosis", () => {
  for (const failureClass of ["upstream_http_response", "post_response_local", "pre_response_transport", undefined] as const) {
    const next = proxyFailureNextAction(failureClass ? { failureClass } : null);
    assert.ok(next.startsWith(AGENT_STEP), next);
    assert.ok(next.length > AGENT_STEP.length, "the diagnosis follows");
  }
});

function proxyFailure(proxy: Parameters<typeof proxyFailureNextAction>[0]) {
  return {
    status: 503,
    error: "upstream HTTP response failed",
    errorCode: "agent_proxy_failed",
    suggestedNextAction: null,
    proxy,
  };
}

test("upstream_http_response: next action sends the reader to the server side, not the proxy transport log", () => {
  const err = apiFailureError(
    proxyFailure({
      layer: "local_daemon_proxy",
      correlationId: "259de033fbf60c5c",
      failureClass: "upstream_http_response",
      causeCode: "HTTP_503",
      routeFamily: "agent-api/events",
      upstreamLayer: "http_status",
      upstreamStatus: 503,
      responseStarted: true,
      responseComplete: true,
    }),
    "SEARCH_FAILED",
  );
  assert.equal(err.code, "PROXY_5XX");
  const next = err.suggestedNextAction ?? "";
  assert.match(next, /HTTP 503/);
  assert.match(next, /discarded the upstream response body/);
  assert.match(next, /correlation id is local to this daemon/);
  assert.match(next, /trace id/);
  assert.match(next, /server-side trace/);
  assert.match(next, /attribution stays unknown/);
  assert.doesNotMatch(next, /inspect daemon proxy transport logs/);
  // The correlation id is never sent upstream (the proxy forwards traceparent),
  // so the copy must not present it as a server-side lookup key.
  assert.doesNotMatch(next, /correlation id against the server/);
});

test("pre_response_transport: next action keeps the proxy transport log hint (that log carries the transport cause)", () => {
  const err = apiFailureError(
    proxyFailure({
      layer: "local_daemon_proxy",
      correlationId: "eb15805d2c86f215",
      failureClass: "pre_response_transport",
      causeCode: "ETIMEDOUT",
      routeFamily: "agent-api/events",
      responseStarted: false,
      responseComplete: false,
    }),
    "READ_FAILED",
  );
  assert.equal(err.code, "PROXY_5XX");
  assert.equal(err.suggestedNextAction, TRANSPORT_LOG_HINT);
});

test("mid_response_transport and missing diagnostics fall back to the transport log hint", () => {
  assert.equal(proxyFailureNextAction({ failureClass: "mid_response_transport" }), TRANSPORT_LOG_HINT);
  assert.equal(proxyFailureNextAction(null), TRANSPORT_LOG_HINT);
  assert.equal(proxyFailureNextAction(undefined), TRANSPORT_LOG_HINT);
});

test("upstream_http_response without a numeric upstream status still names the discarded body", () => {
  const next = proxyFailureNextAction({ failureClass: "upstream_http_response" });
  assert.match(next, /relayed a 5xx from upstream/);
  assert.match(next, /discarded the upstream response body/);
});

test("an explicit caller or upstream next action still wins over the default", () => {
  const upstream = apiFailureError(
    { ...proxyFailure({ failureClass: "upstream_http_response", upstreamStatus: 503 }), suggestedNextAction: "Retry after the server reports healthy." },
    "X",
  );
  assert.equal(upstream.suggestedNextAction, "Retry after the server reports healthy.");
  const caller = apiFailureError(
    proxyFailure({ failureClass: "upstream_http_response", upstreamStatus: 503 }),
    "X",
    { suggestedNextAction: "Caller-specific guidance." },
  );
  assert.equal(caller.suggestedNextAction, "Caller-specific guidance.");
});

test("non-proxy 5xx gets no default next action", () => {
  const err = apiFailureError({ status: 502, error: "bad gateway", errorCode: null, suggestedNextAction: null, proxy: null }, "X");
  assert.equal(err.code, "SERVER_5XX");
  assert.equal(err.suggestedNextAction, undefined);
});

test("post_response_local points at the local daemon, not the server (task #369)", () => {
  const action = proxyFailureNextAction({ failureClass: "post_response_local" });
  assert.notEqual(action, TRANSPORT_LOG_HINT);
  assert.match(action, /local daemon fault, not a server or network failure/);
  assert.doesNotMatch(action, /before attributing it to the server/);
});

// Core's write budgets (the server's agentApiWriteLimits.ts): a 429 RATE_LIMITED
// says how long to wait and is retryable, whichever command got it.
const RATE_LIMITED_BODY = {
  error: "This agent made too many task changes: the limit is 120 a minute. Retry in 23 seconds.",
  code: "RATE_LIMITED",
  details: { operation: "tasks.assign", limit: 120, windowSeconds: 60, retryAfterSeconds: 23 },
};

test("a 429 RATE_LIMITED: the Server's sentence, retryable, the wait in the next action", () => {
  const err = apiFailureError(
    { status: 429, error: RATE_LIMITED_BODY.error, errorCode: "RATE_LIMITED", suggestedNextAction: null, errorBody: RATE_LIMITED_BODY },
    "ASSIGN_FAILED",
  );
  assert.equal(err.code, "RATE_LIMITED");
  assert.equal(err.message, RATE_LIMITED_BODY.error);
  assert.equal(err.retryable, true);
  assert.equal(err.suggestedNextAction, "Wait 23 seconds, then run the same command again (the refused request changed nothing).");
});

test("a 429 RATE_LIMITED whose sentence isn't one short line gets a stand-in from its details", () => {
  const err = rateLimitedResponseError({ status: 429, errorBody: { ...RATE_LIMITED_BODY, error: "line one\nline two" } });
  assert.ok(err);
  assert.equal(err.message, "Too many writes of this kind: the limit is 120 per 60 seconds. Retry in 23 seconds.");
  assert.equal(err.retryable, true);
});

test("not a 429 RATE_LIMITED body: no rate-limit error", () => {
  assert.equal(rateLimitedResponseError({ status: 429, errorBody: { error: "slow down", code: "BUSY" } }), null);
  assert.equal(rateLimitedResponseError({ status: 400, errorBody: RATE_LIMITED_BODY }), null);
});
