export type ActionCardMessageKey = (typeof ACTION_CARD_MESSAGE_KEYS)[number];

const KEYS: ReadonlySet<string> = new Set(ACTION_CARD_MESSAGE_KEYS);

/** Whether `key` is in the table. A plain boolean, not a type guard: as a zod refine it must not narrow the schema's output type. */
export function isActionCardMessageKey(key: string): boolean {
  return KEYS.has(key);
}
