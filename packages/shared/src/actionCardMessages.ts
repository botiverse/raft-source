export type ActionCardMessageKey = keyof typeof ACTION_CARD_MESSAGES;
/** A key split out of a web plural: `actionCard.x` for `actionCard.x.one` / `actionCard.x.other`. */
export type ActionCardPluralMessageKey = {
  [K in ActionCardMessageKey]: K extends `${infer Base}.other` ? (typeof ACTION_CARD_MESSAGES)[K] extends { branch: string } ? Base : never : never;
}[ActionCardMessageKey];

const entryOf = (key: string): ActionCardMessageEntry | undefined =>
  Object.hasOwn(ACTION_CARD_MESSAGES, key) ? (ACTION_CARD_MESSAGES as Record<string, ActionCardMessageEntry>)[key] : undefined;

const copyParams = (params?: Record<string, ActionCardSpecMsgParam>) =>
  params ? { params: Object.fromEntries(Object.entries(params).map(([name, value]) => [name, typeof value === "object" ? { ...value } : value])) } : {};

/** A Msg with every locale the table has for `key`. Params are data: the client fills them in as plain text. */
export function actionCardMsg(key: ActionCardMessageKey, params?: Record<string, ActionCardSpecMsgParam>): ActionCardSpecMsg {
  const entry: ActionCardMessageEntry = ACTION_CARD_MESSAGES[key];
  return { key, text: { ...entry.text }, ...copyParams(params) };
}

/**
 * A Msg for copy the web writes as an ICU plural on `countParam`: each locale
 * gets the branch its own plural rules pick for `count` (Intl.PluralRules,
 * as formatjs), else its `other`. The key names the branch English picks.
 */
export function actionCardPluralMsg(
  base: ActionCardPluralMessageKey,
  countParam: string,
  count: number,
  params: Record<string, ActionCardSpecMsgParam> = {},
): ActionCardSpecMsg {
  const branchKey = (locale: DisplayLocale) => {
    const own = `${base}.${new Intl.PluralRules(DISPLAY_LOCALE_INFO[locale].tag).select(count)}`;
    return entryOf(own) ? own : `${base}.other`;
  };
  const text: Record<string, string> = {};
  for (const locale of DISPLAY_LOCALES) {
    const own = entryOf(branchKey(locale))?.text[locale];
    const template = own ?? entryOf(`${base}.other`)?.text[locale];
    if (template !== undefined) text[locale] = template;
  }
  return { key: branchKey("en"), text: text as ActionCardSpecMsg["text"], ...copyParams({ ...params, [countParam]: count }) };
}
