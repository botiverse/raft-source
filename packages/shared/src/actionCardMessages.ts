// The copy of Raft's first-party action cards (`action-card.v1`), with a
// template per display locale. A card is broadcast to a whole channel, so it
// carries its translations (actionCardSpec.ts, Msg); this table is where the
// server's builders (actionCardSpecBuilder.ts) take them from.
//
// The web catalogs (packages/web/src/i18n/messages) are the source of this
// copy, and this table mirrors them by id: `source` is the web id an entry
// copies, and the web test actionCardMessages.parity checks every entry
// against it in every locale, so the two cannot drift. The conversion: a
// web id that already has an action-card key shape keeps it, any other gets
// `actionCard.` in front; the web's rich-text `<n>` tags are dropped (the
// client styles params itself); an ICU plural becomes one key per branch
// (`<key>.one`, `<key>.other`, `#` -> `{param}`), and actionCardPluralMsg
// picks the branch per locale as formatjs does. The keys are English's
// branches plus any locale's `one`/`other`; another branch (Russian
// `few`/`many`) falls back to `<key>.other`, so that text reads right for any
// count. A locale the web catalog
// lacks is absent here (the client shows English). `source: null` is
// server-only copy, which has no web id: it is translated here, and a locale
// an entry lacks shows English.

import type { ActionCardSpecMsg, ActionCardSpecMsgParam } from "./actionCardSpec";
import { DISPLAY_LOCALES, DISPLAY_LOCALE_INFO, type DisplayLocale } from "./displayLocales";

