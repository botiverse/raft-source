import {
  buildKitchenSink,
  buildRuntimeFormVisualCases,
  KITCHEN_SINK_PAGE_NAMES,
  REAL_FORM_VISUAL_VALUES,
  realFormVisualState,
  realFormVisualStateFile,
  kitchenSinkFormFile,
  kitchenSinkRuntimeId,
  kitchenSinkStateFile,
  RUNTIME_FORM_VISUAL_CASES_FILE,
  runtimeFormV3SourceFixtureName,
} from "../src/kitchenSink";

const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;

/**
 * Every generated fixture by file name, and the kitchen-sink source files in
 * `fixtureNames` that are no longer generated (a removed row).
 */
export function kitchenSinkOutputs(
  fixtureNames: readonly string[],
  readFixture: (name: string) => unknown,
): { outputs: Record<string, string>; stale: string[] } {
  const outputs: Record<string, string> = {};
  for (const page of KITCHEN_SINK_PAGE_NAMES) {
    const { form, sources, state } = buildKitchenSink(page);
    outputs[kitchenSinkFormFile(page)] = json(form);
    outputs[kitchenSinkStateFile(page)] = json(state);
    for (const [sourceId, source] of Object.entries(sources)) {
      outputs[runtimeFormV3SourceFixtureName(kitchenSinkRuntimeId(page), sourceId)] = json(source);
    }
  }
  for (const runtimeId of Object.keys(REAL_FORM_VISUAL_VALUES)) {
    outputs[realFormVisualStateFile(runtimeId)] = json(realFormVisualState(runtimeId));
  }
  outputs[RUNTIME_FORM_VISUAL_CASES_FILE] = json({
    $comment: "Generated by packages/runtime-form/kitchen-sink/generate.ts. Do not edit. Every runtime form visual case: the kitchen sink pages and each server-produced v3 create form, with the fixture of each option source it names (file names relative to this directory). Web (packages/web/visual-testing/RuntimeFormCases.tsx) and mobile render these.",
    cases: buildRuntimeFormVisualCases([...fixtureNames, ...Object.keys(outputs)], readFixture),
  });
  const stale = fixtureNames.filter((name) => (name.startsWith("kitchen-sink") || name.endsWith(".visual-state.v3.json")) && !(name in outputs));
  return { outputs, stale };
}
