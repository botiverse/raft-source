  const [run] = await db.insert(raftbenchLatestRuns).values({ serverId, agentId: agent.id, revision: 1, status: "queued", from: new Date("2026-10-17T00:00:00Z"), to: new Date("2026-10-18T00:00:00Z") }).returning();
  const credential = await mintAgentCredential({ agentId: agent.id, scopes: ["read", "raftbench"], name: "Synthetic analysis", issuedVia: "human", createdByUserId: owner.id });
  const unlistedId = randomUUID();
  await db.insert(servers).values({ id: unlistedId, ownerId: owner.id, name: "Unlisted synthetic", slug: `unlisted-${unlistedId.slice(0, 8)}` });
  const [unlistedAgent] = await db.insert(agents).values({ serverId: unlistedId, name: "UnlistedService", runtime: "external" }).returning();
  const unlistedKey = await mintAgentCredential({ agentId: unlistedAgent.id, scopes: ["raftbench"], name: "Unlisted synthetic", issuedVia: "human", createdByUserId: owner.id });
  const notEnrolled = await fetch(`${app.baseUrl}/internal/agent-api/raftbench/context`, { headers: { Authorization: `Bearer ${unlistedKey.apiKey}` } });
  expect(notEnrolled.status).toBe(403);
  expect((await notEnrolled.json()).code).toBe("raftbench_server_not_allowed");
  const headers = { Authorization: `Bearer ${credential.apiKey}`, "Content-Type": "application/json" };
  const call = (path: string, body?: unknown) => fetch(`${app.baseUrl}/internal/agent-api/${path}`, { headers, method: body === undefined ? "GET" : "POST", ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  const ordinary = await mintAgentCredential({ agentId: agent.id, scopes: ["read", "send", "server", "tasks"], name: "Alternate credential", issuedVia: "human", createdByUserId: owner.id });
  const missingCapability = await fetch(`${app.baseUrl}/internal/agent-api/raftbench/context`, { headers: { Authorization: `Bearer ${ordinary.apiKey}` } });
  expect(missingCapability.status).toBe(403);
  expect((await missingCapability.json()).code).toBe("capability_not_authorized");
  const notHosted = await call(`raftbench/context?runId=${run.runId}`);
  expect(notHosted.status).toBe(403);
  expect((await notHosted.json()).code).toBe("raftbench_service_credential_required");
  await db.insert(raftbenchServiceAgents).values({ serverId, agentId: agent.id });
  await expect(mintAgentCredential({ agentId: agent.id, scopes: ["read", "send"], issuedVia: "human", createdByUserId: owner.id })).rejects.toThrow("raftbench_service_credential_scope_invalid");
  await db.insert(agentRuntimeProvisions).values({ agentId: agent.id, serverId, provider: "antiproton", state: "active", provisionedProfile: "raftbench_service", credentialId: credential.credentialId, provisionedName: "Synthetic analysis", provisionedInstructions: "Synthetic test only" });
  const alternateSend = await fetch(`${app.baseUrl}/internal/agent-api/send`, { method: "POST", headers: { Authorization: `Bearer ${ordinary.apiKey}`, "Content-Type": "application/json" }, body: JSON.stringify({ target: "#synthetic-qa", content: "Synthetic must not send" }) });
  expect(alternateSend.status).toBe(403);
  expect((await alternateSend.json()).code).toBe("raftbench_read_only");
  const identity = await call("");
  expect(identity.status).toBe(200);
  expect((await identity.json()).agentId).toBe(agent.id);
  __setAppWebhookEncryptionKeyForTests(Buffer.alloc(32, 9));
  onTestFinished(() => __setAppWebhookEncryptionKeyForTests(null));
  const oldProviderToken = process.env.ANTIPROTON_PROVISIONING_TOKEN;
  process.env.ANTIPROTON_PROVISIONING_TOKEN = "synthetic-provider-token";
  onTestFinished(() => { if (oldProviderToken === undefined) delete process.env.ANTIPROTON_PROVISIONING_TOKEN; else process.env.ANTIPROTON_PROVISIONING_TOKEN = oldProviderToken; });
  const secret = "Q2hvb3NlLWEtcmFuZG9tLXNlY3JldC1vZi0zMi1ieXRlcw_x";
  const webhook = (method: string, url?: string) => fetch(`${app.baseUrl}/internal/agent-api/push-webhook`, { method, headers, ...(url ? { body: JSON.stringify({ url, secret }) } : {}) });
  for (const url of ["https://canary.antiproton.ai/hooks/synthetic", "https://outside.example/hook", "https://preview.antiproton.ai.outside.example/hook", "https://preview.antiproton.ai@outside.example/hook", "http://preview.antiproton.ai/hook", "https://user@preview.antiproton.ai/hook", "https://preview.antiproton.ai/other", "https://preview.antiproton.ai/hooks/", "https://preview.antiproton.ai/hooks/synthetic?x=1", "https://preview.antiproton.ai/hooks/synthetic#x", "not a URL"]) {
    const refused = await webhook("PUT", url);
    expect(refused.status, url).toBe(403);
    const error = await refused.json();
    expect(error.code).toBe("raftbench_read_only");
    expect(error.error).toContain("/hooks/<id>");
    expect(error.suggestedNextAction).toContain("configured Antiproton provider hook URL");
  }
  delete process.env.ANTIPROTON_PROVISIONING_TOKEN;
  expect((await webhook("PUT", "https://preview.antiproton.ai/hooks/synthetic")).status).toBe(403);
  process.env.ANTIPROTON_PROVISIONING_TOKEN = "synthetic-provider-token";
  const registered = await webhook("PUT", "https://preview.antiproton.ai/hooks/synthetic");
  expect(registered.status, await registered.clone().text()).toBe(200);
  expect(await registered.text()).not.toContain(secret);
  const status = await webhook("GET");
  expect(status.status).toBe(200);
  expect((await status.json()).registered).toBe(true);
  expect((await webhook("DELETE")).status).toBe(204);
  expect((await (await webhook("GET")).json()).registered).toBe(false);
  const outside = await call(`raftbench/context?runId=${randomUUID()}`);
  expect(outside.status).toBe(404);
  const notOwned = await outside.json();
  expect(notOwned.code).toBe("raftbench_run_not_owned");
  process.env.DEPLOYMENT_ENV = "production";
  const prod = await call("raftbench/context");
  expect(prod.status).toBe(403);
  expect((await prod.json()).code).toBe("raftbench_server_not_allowed");
  process.env.DEPLOYMENT_ENV = "staging";
  const denied = await call("send", { target: "#synthetic-qa", content: "Should not send" });
  expect(denied.status).toBe(403);
  expect((await denied.json()).code).toBe("raftbench_read_only");
  await db.update(raftbenchLatestRuns).set({ from: new Date("2026-10-17T23:59:00Z") }).where(eq(raftbenchLatestRuns.serverId, serverId));
  const empty = await (await call(`raftbench/context?runId=${run.runId}`)).json();
  expect(empty.coverage).toMatchObject({ fetchedMessages: 0, exhausted: true });
  const emptyComplete = await call("raftbench/submit", { runId: run.runId, revision: 1, status: "complete", patterns: [], gaps: [] });
  expect(emptyComplete.status).toBe(422);
  const emptyIssue = (await emptyComplete.json()).issues[0];
  expect(emptyIssue.message).toContain("nothing was analyzed");
  expect(emptyIssue.suggestedFix).toBe("Change status to incomplete, set reason to: No messages were read in this window; nothing was analyzed. Leave patterns empty.");
  const emptyPartial = await call("raftbench/submit", { runId: run.runId, revision: 1, status: "incomplete", reason: "No messages were read in this window; nothing was analyzed.", patterns: [], gaps: ["missing_tool_outcomes"] });
  expect(emptyPartial.status).toBe(200);
  expect((await db.select().from(raftbenchLatestRuns).where(eq(raftbenchLatestRuns.serverId, serverId)))[0].status).toBe("partial");
  await db.update(raftbenchLatestRuns).set({ from: run.from, status: "queued", exhausted: false, report: null, submissionHash: null, receiptId: null }).where(eq(raftbenchLatestRuns.serverId, serverId));
  const source = await call(`raftbench/context?runId=${run.runId}`);
  const context = await source.json();
  expect(source.status, JSON.stringify(context)).toBe(200);
  expect(context.coverage).toMatchObject({ fetchedMessages: 100, exhausted: false });
  expect(context.sourceText).toContain(`[target=#synthetic-qa msg=${message.id}`);
  expect(context.sourceText).toContain("time=2026-10-17 12:00:00Z");
  expect(context.sourceText).not.toContain("Coverage:");
  expect(context.coverage.stopReason).toBe("more_pages");
  expect(context.sourceText).not.toContain("fixture@example.invalid");
  expect(context.sourceText).not.toContain("sk_agent_SYNTHETIC_ONLY_NOT_REAL_0000");
  expect(context.sourceText).not.toContain("192.0.2.1");
  expect(context.sourceText).not.toContain("2001:db8::1");
  // Task/action metadata bumps updatedAt but does not change the material.
  await db.update(messages).set({ updatedAt: new Date(Date.now() + 500), taskStatus: "done", actionMetadata: { syntheticTaskStatus: "done" } }).where(eq(messages.id, message.id));
  const repeated = await call(`raftbench/context?runId=${run.runId}`);
  expect((await repeated.json()).coverage.fetchedMessages).toBe(100);
  const premature = await call("raftbench/submit", { runId: run.runId, revision: 1, status: "complete", patterns: [], gaps: [] });
  expect(premature.status).toBe(422);
  expect((await premature.json()).issues[0].path).toBe("status");
  const second = await call(`raftbench/context?runId=${run.runId}&cursor=${encodeURIComponent(context.nextCursor)}`);
  const lastPage = await second.json();
  expect(lastPage.coverage).toMatchObject({ fetchedMessages: 102, exhausted: true });
  expect(lastPage.nextCursor).toBeNull();
  expect(lastPage.coverage.stopReason).toBe("window_end");
  // An exhausted tail cannot hide an unknown skipped chunk in this window.
  const inWindow = { from: run.from.toISOString(), to: run.to.toISOString(), messages: 3 };
  await db.update(raftbenchLatestRuns).set({ skippedRanges: Array.from({ length: 10 }, () => inWindow) }).where(eq(raftbenchLatestRuns.serverId, serverId));
  const skippedContext = await (await call(`raftbench/context?runId=${run.runId}&cursor=${encodeURIComponent(context.nextCursor)}`)).json();
  expect(skippedContext.coverage).toMatchObject({ exhausted: false, skippedChunks: 10, stopReason: "window_end" });
  expect(skippedContext.coverage.notRead.filter((line: string) => line.includes("skipped after 3"))).toHaveLength(10);
  const skippedComplete = await call("raftbench/submit", { runId: run.runId, revision: 1, status: "complete", patterns: [], gaps: [] });
  expect(skippedComplete.status).toBe(422);
  // A historical range ending exactly at this window's start is outside it.
  const historical = { from: new Date(run.from.getTime() - 60_000).toISOString(), to: run.from.toISOString(), messages: 3 };
  await db.update(raftbenchLatestRuns).set({ skippedRanges: [historical] }).where(eq(raftbenchLatestRuns.serverId, serverId));
  const laterContext = await (await call(`raftbench/context?runId=${run.runId}&cursor=${encodeURIComponent(context.nextCursor)}`)).json();
  expect(laterContext.coverage).toMatchObject({ exhausted: true, skippedChunks: 0 });
  expect(laterContext.coverage.notRead.some((line: string) => line.includes("skipped after 3"))).toBe(false);
  const pattern = { kind: "repeated_clarification", explanation: "Synthetic example: fixture@example.invalid, 2001:db8::1", evidence: [{ target: "#synthetic-qa", messageId: "00000000" }], counterevidence: [{ target: "#other", messageId: message.id }], evidenceLevel: "conversation_only", intent: "unknown", suggestion: "Draft clearer acceptance criteria" };
  const bad = await call("raftbench/submit", { runId: run.runId, revision: 1, status: "complete", patterns: [pattern], gaps: [] });
  const invalid = await bad.json();
  expect(bad.status).toBe(422);
  expect(invalid.issues).toHaveLength(2);
  expect((await db.select().from(raftbenchLatestRuns).where(eq(raftbenchLatestRuns.serverId, serverId)))[0].report).toBeNull();
  const body = { runId: run.runId, revision: 1, status: "complete", patterns: [{ ...pattern, evidence: [{ target: "#synthetic-qa", messageId: message.id.slice(0, 8) }], counterevidence: [] }], gaps: ["missing_tool_outcomes"] };
  const accepted = await call("raftbench/submit", body);
  const receipt = await accepted.json();
  expect(accepted.status, JSON.stringify(receipt)).toBe(200);
  const stored = (await db.select().from(raftbenchLatestRuns).where(eq(raftbenchLatestRuns.serverId, serverId)))[0].report!;
  expect(stored.patterns[0].explanation).not.toContain("fixture@example.invalid");
  expect(stored.patterns[0].explanation).not.toContain("2001:db8::1");
  const replay = await call("raftbench/submit", body);
  expect(await replay.json()).toEqual(receipt);
  const overwrite = await call("raftbench/submit", { ...body, patterns: [] });
  expect(overwrite.status).toBe(409);
  expect((await overwrite.json()).code).toBe("raftbench_submission_conflict");
  const finished = await call(`raftbench/context?runId=${run.runId}`);
  expect((await finished.json()).code).toBe("raftbench_run_finished");
  const stale = await call("raftbench/submit", { ...body, revision: 2 });
  expect(stale.status).toBe(409);
  const conflict = await stale.json();
  expect(conflict.code).toBe("raftbench_revision_conflict");
  await db.update(raftbenchConfigs).set({ enabled: false }).where(eq(raftbenchConfigs.serverId, serverId));
  const withdrawn = await call("raftbench/submit", body);
  expect(withdrawn.status).toBe(409);
  expect((await withdrawn.json()).code).toBe("raftbench_disabled");
  await db.update(raftbenchConfigs).set({ enabled: true }).where(eq(raftbenchConfigs.serverId, serverId));
  await db.update(featureFlags).set({ killSwitch: true }).where(eq(featureFlags.key, "raftbench_overview_v0"));
  const flagOff = await call("raftbench/submit", body);
  expect(flagOff.status).toBe(409);
  expect((await flagOff.json()).code).toBe("raftbench_disabled");
  await db.update(featureFlags).set({ killSwitch: false }).where(eq(featureFlags.key, "raftbench_overview_v0"));
  const budgetRunId = randomUUID();
  await db.update(raftbenchLatestRuns).set({ runId: budgetRunId, status: "queued", fetched: [], skippedRanges: [], exhausted: false, nextSeq: 0, sourceCharacters: 0, report: null, submissionHash: null, receiptId: null }).where(eq(raftbenchLatestRuns.serverId, serverId));
  await db.update(messages).set({ content: "Synthetic long message ".repeat(200) }).where(eq(messages.channelId, channel.id));
  const bounded = await call(`raftbench/context?runId=${budgetRunId}`);
  const budgetContext = await bounded.json();
  expect(budgetContext.coverage.exhausted).toBe(false);
  expect(budgetContext.coverage.fetchedMessages).toBeGreaterThan(0);
  expect(budgetContext.coverage.fetchedMessages).toBeLessThan(100);
  expect(budgetContext.nextCursor).toBeNull();
  expect(budgetContext.coverage.stopReason).toBe("char_limit");
  expect(budgetContext.sourceText).toMatch(/…⟨\d+ more chars⟩/);
  const budgetReplay = await call(`raftbench/context?runId=${budgetRunId}`);
  expect((await budgetReplay.json()).coverage).toEqual(budgetContext.coverage);
  const incomplete = await call("raftbench/submit", { runId: budgetRunId, revision: 1, status: "incomplete", reason: "Source budget reached", patterns: [], gaps: ["budget"] });
