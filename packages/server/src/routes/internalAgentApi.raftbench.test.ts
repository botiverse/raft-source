  const [budgetStored] = await db.select().from(raftbenchLatestRuns).where(eq(raftbenchLatestRuns.serverId, serverId));
  const nextTime = new Date(Date.now() + 16 * 60_000);
  await advanceServer(serverId, nextTime);
  const [continuation] = await db.select().from(raftbenchLatestRuns).where(eq(raftbenchLatestRuns.serverId, serverId));
  expect(continuation.runId).not.toBe(budgetRunId);
  expect(continuation.startAfterSeq).toBe(budgetStored.nextSeq);
  expect(continuation.from).toEqual(budgetStored.from); expect(continuation.to).toEqual(budgetStored.to);
  const continued = await (await call(`raftbench/context?runId=${continuation.runId}`)).json();
  expect(continued.sources.length).toBeGreaterThan(0);
  expect(continued.sources.every((ref: { messageId: string }) => !budgetContext.sources.some((old: { messageId: string }) => old.messageId === ref.messageId))).toBe(true);
  expect(continued.coverage.exhausted).toBe(false);
  expect(continued.coverage.notRead.join(" ")).toContain("Messages earlier in this window");
  const failure = await call("raftbench/submit", { runId: continuation.runId, revision: 1, status: "incomplete", failure: true, reason: "Synthetic model request failed", patterns: [], gaps: [] });
  const failedReceipt = await failure.json();
  expect(failure.status, JSON.stringify(failedReceipt)).toBe(200);
  const failureReplay = await call("raftbench/submit", { runId: continuation.runId, revision: 1, status: "incomplete", failure: true, reason: "Synthetic model request failed", patterns: [], gaps: [] });
