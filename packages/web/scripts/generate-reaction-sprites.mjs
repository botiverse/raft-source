import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(scriptDir, "..");
const sourceRoot = join(webRoot, "assets/reactions");
const svgRoot = join(sourceRoot, "source");
const publicRoot = join(webRoot, "public/reactions");
const generatedRoot = join(webRoot, "src/generated");
const manifestJsonPath = join(publicRoot, "reaction-sprite.manifest.json");
const manifestTsPath = join(generatedRoot, "reactionSpriteManifest.ts");
const spritePath = join(publicRoot, "reaction-sprite.svg");
const tileSize = 24;

const readJson = async (path) => JSON.parse(await readFile(path, "utf8"));

const normalizeSvg = (raw) => raw.trim().replace(/\s+/g, " ");

const extractSvgBody = (raw, source) => {
  const svg = normalizeSvg(raw);
  const match = svg.match(/^<svg\b[^>]*>(.*)<\/svg>$/i);
  if (!match) {
    throw new Error(`Expected ${source} to contain a single root <svg>`);
  }
  return match[1].trim();
};

const buildTsManifest = (manifest) => {
  const json = JSON.stringify(manifest, null, 2)
    .replace(/"([^"]+)":/g, "$1:");
  return [
    "// Generated by packages/web/scripts/generate-reaction-sprites.mjs. Do not edit by hand.",
    "",
    "export interface ReactionSpriteItem {",
    "  id: string;",
    "  emoji: string;",
    "  aliases?: readonly string[];",
    "  label: string;",
    "  x: number;",
    "  y: number;",
    "  width: number;",
    "  height: number;",
    "}",
    "",
    "export interface ReactionSpriteManifest {",
    "  version: number;",
    "  spritePath: string;",
    "  spriteWidth: number;",
    "  spriteHeight: number;",
    "  items: readonly ReactionSpriteItem[];",
    "}",
    "",
    `export const REACTION_SPRITE_MANIFEST = ${json} as const satisfies ReactionSpriteManifest;`,
    "",
    "const reactionSpriteItems = REACTION_SPRITE_MANIFEST.items as readonly ReactionSpriteItem[];",
    "",
    "export const REACTION_SPRITE_ITEMS = Object.fromEntries(",
    "  reactionSpriteItems.flatMap((item) => [",
    "    [item.emoji, item],",
    "    ...(item.aliases ?? []).map((alias) => [alias, item] as const),",
    "  ]),",
    ") as Record<string, ReactionSpriteItem>;",
    "",
  ].join("\n");
};

await rm(publicRoot, { recursive: true, force: true });
await mkdir(publicRoot, { recursive: true });
await mkdir(generatedRoot, { recursive: true });

const definitions = await readJson(join(sourceRoot, "reactions.json"));
const entries = [];

for (const [index, definition] of definitions.entries()) {
  const sourcePath = join(svgRoot, definition.source);
  const svgBody = extractSvgBody(await readFile(sourcePath, "utf8"), definition.source);

  entries.push({
    ...definition,
    x: index * tileSize,
    y: 0,
    width: tileSize,
    height: tileSize,
    svgBody,
  });
}

const manifest = {
  version: 1,
  spritePath: "/reactions/reaction-sprite.svg",
  spriteWidth: entries.length * tileSize,
  spriteHeight: tileSize,
  items: entries.map(({ svgBody: _svgBody, source: _source, ...entry }) => entry),
};

const spriteSvg = [
  `<svg xmlns="http://www.w3.org/2000/svg" fill="none" width="${manifest.spriteWidth}" height="${manifest.spriteHeight}" viewBox="0 0 ${manifest.spriteWidth} ${manifest.spriteHeight}">`,
  ...entries.map((entry) => `  <g id="${entry.id}" transform="translate(${entry.x} 0)">${entry.svgBody}</g>`),
  "</svg>",
  "",
].join("\n");

await writeFile(spritePath, spriteSvg);
await writeFile(manifestJsonPath, `${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(manifestTsPath, buildTsManifest(manifest));

console.log(`Generated ${relative(webRoot, spritePath)}`);
console.log(`Generated ${relative(webRoot, manifestJsonPath)}`);
console.log(`Generated ${relative(webRoot, manifestTsPath)}`);
